-- Индекс под самый ходовой запрос: список по статусу, новые сверху.
--
-- Без него список уходил в последовательный скан всей таблицы: на 5340 тикетах
-- 4179 строк перебирались, чтобы отдать двадцать. С индексом читаются ровно
-- двадцать — 3.5 мс против 0.085 мс, и разница растёт линейно с объёмом.
--
-- deleted_at в условии обязателен: запросы всегда его содержат, а частичный
-- индекс без него не подойдёт.
create index if not exists tickets_status_created
  on tickets (status, created_at desc)
  where deleted_at is null;

-- То же для выборки «мои тикеты»: сервер подставляет исполнителя из ключа,
-- и это второй по частоте фильтр после статуса.
create index if not exists tickets_assignee_created
  on tickets (assignee, created_at desc)
  where deleted_at is null;
