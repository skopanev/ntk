-- Жизненный цикл модуля: действующий или отправленный в архив.
--
-- Прежнее поведение — отвергать замену списка, если исчезнувший модуль ещё
-- используется — защищало ссылки, но останавливало работу: список приходит
-- снаружи и меняется сам по себе, а тикеты, заведённые на исчезнувший модуль,
-- никуда не деваются. Отказ означал, что реестр нельзя обновить, пока кто-то
-- вручную не переназначит десятки тикетов.
--
-- Архив разделяет два разных вопроса. «Существует ли модуль» — да, потому что
-- на него ссылаются, и ссылка обязана остаться рабочей. «Можно ли выбрать его
-- для новой работы» — нет, он исчез из источника. Прежняя схема отвечала на
-- оба вопроса одним фактом наличия строки и потому не могла ответить верно.
alter table modules add column if not exists archived_at timestamptz;

-- Отбор действующих — самый частый запрос: он нужен на каждом назначении.
create index if not exists modules_active on modules (project_id, name)
  where archived_at is null;
