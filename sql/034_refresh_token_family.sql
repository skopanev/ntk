-- Ротация refresh-токенов с обнаружением повторного использования.
--
-- До сих пор обмен выдавал новый refresh, но СТАРЫЙ продолжал работать все
-- тридцать дней. Украденный токен поэтому ничем себя не выдавал: и вор, и
-- владелец обновлялись параллельно, и в журнале это выглядело как один
-- активный клиент.
--
-- Семья связывает всю цепочку обменов одного входа. Повторное использование
-- уже потраченного refresh означает, что копия токена есть у двоих, и
-- единственный безопасный ответ — погасить цепочку целиком, включая свежий:
-- кто из двоих настоящий владелец, сервер не знает, а войти заново может
-- только он. Так устроено в RFC 9700; это же уже работает в соседнем сервисе.
alter table core.oauth_tokens add column if not exists family text;

-- Выданным до этой миграции семья назначается своя, по самому токену: иначе
-- один null объединил бы их все в одну цепочку, и первый же повтор погасил бы
-- сессии всем сразу.
update core.oauth_tokens set family = token_hash where family is null;

create index if not exists oauth_tokens_family on core.oauth_tokens (family)
  where revoked_at is null;
