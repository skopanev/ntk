-- Обход тикетов: сеанс проверки, а не свойство человека.
--
-- Ключ — идентификатор сеанса, который придумывает клиент. Иначе два агента под
-- одним ключом делят одну память обхода и получают ОДИН И ТОТ ЖЕ тикет: оба
-- читают список показанного до того, как любой из них его дополнил. Это ровно
-- та гонка, из-за которой мы уехали с Notion, только на другом столе.
--
-- Хранится на сервере, а не в файле у клиента, потому что ходить хотят из двух
-- мест: из терминала и из Claude. Файл на машине означал бы два независимых
-- обхода, каждый со своей правдой.
--
-- Запоминается ПОКАЗАННОЕ, а не место в списке. Со снимком набора первая же
-- правка сдвигает остальных и шаг перескакивает через соседа — молча. Со
-- списком показанного исчезновение соседа не сдвигает ничего, а заведённый
-- минуту назад тикет попадает в обход сам.
create table if not exists core.walk_state (
  walk_id    text primary key,
  user_id    text not null references core.users(id) on delete cascade,
  workspace  text not null,
  -- Чем отбирали: показывается человеку, чтобы он знал, по чему идёт.
  what       text not null default '',
  seen       text[] not null default '{}',
  updated_at timestamptz not null default now()
);

-- Чужой обход не открывается даже по угаданному идентификатору: владелец
-- проверяется всегда.
create index if not exists walk_state_owner on core.walk_state (user_id, updated_at);

grant select, insert, update, delete on core.walk_state to ntk_api;
