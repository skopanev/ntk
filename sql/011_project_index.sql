-- Выборка по проекту без статуса уходила в последовательный скан.
--
-- Индекс (project_id, status) уже был, но не подходил: в нём нет deleted_at,
-- а запросы всегда его содержат, и сортировка по дате требовала отдельного
-- прохода. Замерено: 4.8 мс скана против 0.2 мс по индексу.
--
-- Порядок колонок не случаен: сначала то, по чему фильтруют, потом то, по чему
-- сортируют. Тогда индекс отдаёт уже отсортированное, и сортировки нет вовсе.
create index if not exists tickets_project_created
  on tickets (project_id, created_at desc)
  where deleted_at is null;
