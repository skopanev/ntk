-- Пределы длины полей при записи.
--
-- Политика живёт в ДАННЫХ, как status_policy и tag_requirements: владелец
-- меняет порог одним UPDATE, без выпуска. Это не про удобство правки, а про то,
-- что порог придётся двигать: он выбран против сегодняшней привычки писать, и
-- подстраивать его будут по тому, как флот подтянется.
--
-- Зачем предел вообще: на замере 5781 живого тикета медиана тела 3755 символов,
-- p99 — 69057, максимум — 372896. Тикет на треть миллиона знаков не читается
-- человеком, не помещается в контекст целиком и не векторизуется осмысленно:
-- это не постановка, а свалка. Предел заставляет либо разбить работу на
-- атомарные тикеты, либо унести объём во вложение — и то и другое лучше.
create table if not exists write_limits (
  field   text primary key,
  max_len int  not null check (max_len > 0)
);

-- 2000 на тело — решение владельца, принятое ПОСЛЕ замера: он отвергает 65%
-- тикетов, написанных по сегодняшней привычке, и это осознанная смена правил
-- письма, а не ограждение от выбросов.
-- 256 на заголовок отвергает 0.12% (семь тикетов из 5781) — ровно выбросы;
-- 128 отверг бы 6% при p90 = 117, то есть резал бы осмысленные заголовки.
insert into write_limits (field, max_len) values ('body', 2000), ('title', 256)
  on conflict (field) do nothing;
