-- Удаление тикета — мягкое, отметкой времени.
--
-- Выбор между настоящим delete и отметкой решается не вкусом, а тем, что
-- стоит за строкой. Настоящее удаление уносит с собой рёбра зависимостей:
-- у deps стоит on delete cascade, поэтому «удалить один тикет» тихо означало
-- бы «снять зависимость у всех, кто его ждал». Тикет, который чего-то ждал,
-- внезапно оказывается готовым к работе — и никто не узнает почему.
--
-- В Notion это была корзина с восстановлением, и люди на неё полагались:
-- удаляли, потом искали. Отметка сохраняет ту же возможность, а команда
-- получает смысл «убрать с глаз», а не «стереть безвозвратно».
--
-- Цена честная и её надо назвать: каждый запрос обязан исключать удалённые,
-- иначе они всплывут в списках. Поэтому частичные индексы под очередь и
-- выборки пересобраны с этим условием.
alter table tickets add column if not exists deleted_at timestamptz;

drop index if exists tickets_open_queue;
create index if not exists tickets_open_queue
  on tickets (priority, created_at) where status = 'open' and deleted_at is null;

create index if not exists tickets_alive on tickets (id) where deleted_at is null;
