-- Проверка формата id снова оказалась строже данных. На полном снимке из 2157
-- тикетов её не прошли два: workflows-pmstate-gc1 (два дефиса, хвост в три
-- символа) и funnel7-mamma-mia. Оба заведены руками через --ticket-id, и оба
-- живые.
--
-- Вывод, ради которого это записано: формат id — не наше правило, а
-- наблюдение за данными, и каждый раз, когда мы описывали его строже, чем он
-- есть, спотыкалась миграция, а не пользователь. Поэтому проверка сводится к
-- тому, что действительно обязано выполняться: непустой, без пробелов, из
-- букв, цифр, дефиса и подчёркивания. Всё остальное — соглашение, которое
-- держится договорённостью, а не базой.
alter table tickets drop constraint if exists tickets_id_check;
alter table tickets add constraint tickets_id_check
  check (id ~ '^[A-Za-z0-9_-]{3,64}$');
